-- Agence de départ unique : Mont-de-Marsan (40). La zone dépend du département d'arrivée.
CREATE TABLE zone_departement (
    departement VARCHAR(3) PRIMARY KEY,
    nom         VARCHAR(60) NOT NULL,
    zone        INTEGER     NOT NULL CHECK (zone BETWEEN 1 AND 4)
);

-- Une grille par période. valide_au vide = en vigueur jusqu'à la prochaine.
CREATE TABLE grille (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                VARCHAR(80)   NOT NULL,
    valide_du          DATE          NOT NULL,
    valide_au          DATE,
    minimum_perception NUMERIC(10, 2) NOT NULL,
    prix_hayon         NUMERIC(10, 2) NOT NULL,
    prix_rendez_vous   NUMERIC(10, 2) NOT NULL,
    taux_tva           NUMERIC(5, 2)  NOT NULL,
    CHECK (valide_au IS NULL OR valide_au >= valide_du)
);

CREATE TABLE tranche (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grille_id BIGINT         NOT NULL REFERENCES grille (id),
    zone      INTEGER        NOT NULL CHECK (zone BETWEEN 1 AND 4),
    poids_min NUMERIC(10, 2) NOT NULL,
    poids_max NUMERIC(10, 2) NOT NULL,
    mode      VARCHAR(10)    NOT NULL CHECK (mode IN ('FORFAIT', 'AU_100KG')),
    prix      NUMERIC(10, 2) NOT NULL,
    CHECK (poids_max > poids_min),
    UNIQUE (grille_id, zone, poids_min)
);

-- Taux de surcharge gazole publié chaque mois (mois = premier jour du mois).
CREATE TABLE indice_gazole (
    mois DATE          PRIMARY KEY,
    taux NUMERIC(5, 2) NOT NULL
);

CREATE TABLE devis (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          VARCHAR(20)    UNIQUE,
    cree_le         TIMESTAMP      NOT NULL,
    departement     VARCHAR(3)     NOT NULL REFERENCES zone_departement (departement),
    poids_kg        NUMERIC(10, 2) NOT NULL,
    volume_m3       NUMERIC(10, 3) NOT NULL,
    date_enlevement DATE           NOT NULL,
    hayon           BOOLEAN        NOT NULL,
    rendez_vous     BOOLEAN        NOT NULL,
    grille_id       BIGINT         NOT NULL REFERENCES grille (id),
    zone            INTEGER        NOT NULL,
    poids_taxable   NUMERIC(10, 2) NOT NULL,
    taux_gazole     NUMERIC(5, 2)  NOT NULL,
    total_ht        NUMERIC(10, 2) NOT NULL,
    tva             NUMERIC(10, 2) NOT NULL,
    total_ttc       NUMERIC(10, 2) NOT NULL
);

CREATE TABLE devis_ligne (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devis_id BIGINT         NOT NULL REFERENCES devis (id),
    ordre    INTEGER        NOT NULL,
    libelle  VARCHAR(120)   NOT NULL,
    montant  NUMERIC(10, 2) NOT NULL
);

CREATE INDEX idx_tranche_grille ON tranche (grille_id);
CREATE INDEX idx_devis_cree_le ON devis (cree_le);
